public class AREA1
{
public static void main(String args[])
{
int b=4,h=5,l=10,br=5,r=10;
int ch=3;

switch(ch)
{
case 1: System.out.println("Area of triangle=" +0.5*b*h);
break;
case 2: System.out.println("Area of rectangle=" +l*br);
break;
case 3: System.out.println("Area of circle=" +3.14*r*r);
break;
default: System.out.println("invalid choice");
break;

}
}
}

